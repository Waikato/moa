#!/usr/bin/env python3
"""Checks that the paper uses the current generated tables.

paper/brim_paper.tex has its tables inlined (no \\input), so a table regenerated by the analysis scripts in
paper/tables/ has to be copied into it by hand. This script reports every table of paper/tables/ that does not appear
verbatim in paper/brim_paper.tex, except those the paper does not use as they are (NOT_INLINED).

Usage: python3 analysis/check_paper_tables.py    (exit code 1 if a used table is out of date)
"""
import glob
import os
import sys

EXP_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NOT_INLINED = {
    "sgbt_final.tex": "replaced by sgbt_final_{accuracy,memory,time}.tex in the appendix",
    "sgbt_tuning.tex": "reformatted by hand into the top of Table tab:sgbt-tuning (same numbers)",
    "sgbt_tuning_old.tex": "not used (an earlier tuning)",
}


def main():
    paper = open(os.path.join(EXP_DIR, "paper", "brim_paper.tex")).read()
    stale = []
    for path in sorted(glob.glob(os.path.join(EXP_DIR, "paper", "tables", "*.tex"))):
        name = os.path.basename(path)
        if name in NOT_INLINED:
            print(f"skipped  {name}: {NOT_INLINED[name]}")
        elif open(path).read().rstrip("\n") in paper:
            print(f"ok       {name}")
        else:
            print(f"OUTDATED {name}: not in paper/brim_paper.tex as generated; copy it into the paper")
            stale.append(name)
    print(f"{len(stale)} table(s) out of date" if stale else "all used tables are inlined as generated")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
